"""Tests for MNI transform files (.xfm), including FreeSurfer's talairach.xfm.

No transform file ships with the tests, so files are written by two
literal transcriptions of the upstream writers, which are independent of
the reader: `_libminc` transcribes `output_transform` in libminc's
`volume_io/MNI_formats/gen_xf_io.c` (BIC-MNI/libminc, commit e71e590),
and `_freesurfer` transcribes `ltaMNIwrite` in FreeSurfer's
`utils/transform.cpp` (freesurfer/freesurfer, commit 4f8728e), which
writes `talairach.xfm`. Displacement volumes are written with h5py in the
MINC2 layout that libminc's HDF5 layer writes (`hdf_dim_commit` in
`libsrc/hdf_convenience.c` gives `vector_dimension` a dataset of its
own), and with the NetCDF writer of scipy in the MINC1 layout of
volume_io (`output_mnc.c` gives only the spatial dimensions a variable).
"""

import os
import pickle
from pathlib import Path

import numpy as np
import pytest
import typing_extensions as tx

from brainhops import io
from brainhops.datamodel import transformations as xforms
from brainhops.datamodel.systems import LPSmm, RASmm
from brainhops.io.base.parsers import (
    ParserContentError,
    ParserExistsError,
    ParserNotImplementedError,
    UnrepresentableTransformationError,
    WriterError,
)
from brainhops.io.transformations.minc import (
    XfmAffine,
    XfmGridTransform,
    XfmMetadata,
    XfmRaw,
    XfmTransform,
)

h5py = pytest.importorskip("h5py")
pytest.importorskip("nibabel")

RAS = dict(input=RASmm(), output=RASmm())

TALAIRACH = np.array(
    [
        [1.05, 0.01, -0.02, -1.5],
        [-0.01, 1.10, 0.08, -17.25],
        [0.02, -0.09, 1.02, 12.75],
    ]
)
"""A matrix in the range of a `talairach.xfm`, made up for the tests."""

SECOND = np.array(
    [[0.0, -1.0, 0.0, 3.0], [1.0, 0.0, 0.0, -2.0], [0.0, 0.0, 2.0, 1.0]]
)

SHAPE = (4, 5, 6)
"""The shape of the grid of a displacement volume, indexed `[x, y, z]`."""

_ANGLE = 0.3
COSINES = (
    (np.cos(_ANGLE), np.sin(_ANGLE), 0.0),
    (-np.sin(_ANGLE), np.cos(_ANGLE), 0.0),
    (0.0, 0.0, 1.0),
)
"""The direction cosines of `xspace`, `yspace` and `zspace`."""

START = (-10.0, 5.0, 2.0)
STEP = (2.0, -1.5, 3.0)

FILE_ORDER = ("zspace", "yspace", "xspace", "vector_dimension")
"""The order of the dimensions that libminc writes for a grid."""


# ----------------------------------------------------------------------
#   WRITERS
# ----------------------------------------------------------------------


def _libminc(
    blocks: tx.Sequence[tx.Tuple[str, tx.Any, bool]],
    comments: tx.Optional[str] = None,
) -> str:
    """Write a file as libminc's `output_transform` writes it.

    Each block is `(type, parameter, inverted)`, where the parameter of a
    linear transform is its `(3, 4)` matrix and that of a grid transform
    the name of its volume. Like libminc, an inverted linear transform is
    written as its inverse matrix, without a flag.
    """
    text = "MNI Transform File\n"
    if comments is not None:
        text += "%" + comments.replace("\n", "\n%")
        if not comments.endswith("\n"):
            text += "\n"
    text += "\n"
    for kind, parameter, inverted in blocks:
        if kind == "linear":
            matrix = np.asarray(parameter, float)
            if inverted:
                homogeneous = np.vstack([matrix, [0, 0, 0, 1]])
                matrix = np.linalg.inv(homogeneous)[:3]
            text += "Transform_Type = Linear;\nLinear_Transform =\n"
            for i in range(3):
                # The C format of libminc, kept as it is written.
                text += " %.15g %.15g %.15g %.15g" % tuple(matrix[i])  # noqa: UP031
                if i == 2:
                    text += ";"
                text += "\n"
        else:
            text += "Transform_Type = Grid_Transform;\n"
            if inverted:
                text += "Invert_Flag = True;\n"
            text += f"Displacement_Volume = {parameter};\n"
    return text


def _freesurfer(matrix: np.ndarray, src: str, dst: str) -> str:
    """Write a linear file as FreeSurfer's `ltaMNIwrite` writes it."""
    text = "MNI Transform File\n"
    text += f"%Generated by mri_robust_register src {src} dst {dst}\n"
    text += "\n"
    text += "Transform_Type = Linear;\n"
    text += "Linear_Transform =\n"
    for row in range(3):
        # The C format of FreeSurfer, kept as it is written.
        text += "%13.8f %13.8f %13.8f %13.8f " % tuple(matrix[row])  # noqa: UP031
        if row == 2:
            text += ";"
        text += "\n"
    return text


def _field(seed: int = 0, scale: float = 1.0) -> np.ndarray:
    """Return displacements in millimetres, indexed `[x, y, z, c]`."""
    return np.random.default_rng(seed).normal(size=SHAPE + (3,)) * scale


def _write_grid(
    path: Path,
    field: np.ndarray,
    order: tx.Sequence[str] = FILE_ORDER,
    step: tx.Sequence[float] = STEP,
) -> None:
    """Write a MINC2 displacement volume in the layout of libminc."""
    axes = {"xspace": 0, "yspace": 1, "zspace": 2, "vector_dimension": 3}
    stored = np.transpose(field, [axes[n] for n in order]).astype("float32")
    with h5py.File(path, "w") as f:
        root = f.create_group("minc-2.0")
        dimensions = root.create_group("dimensions")
        for i, name in enumerate(order):
            dataset = dimensions.create_dataset(name, data=np.int32(0))
            dataset.attrs["length"] = np.int32(stored.shape[i])
            if name != "vector_dimension":
                axis = axes[name]
                dataset.attrs["start"] = START[axis]
                dataset.attrs["step"] = step[axis]
                dataset.attrs["direction_cosines"] = np.asarray(COSINES[axis])
        image = root.create_group("image/0")
        dataset = image.create_dataset("image", data=stored)
        dataset.attrs["dimorder"] = np.bytes_(",".join(order).encode())
        for name in ("image-min", "image-max"):
            image.create_dataset(name, data=np.zeros(stored.shape[0]))


def _write_minc1_grid(path: Path, field: np.ndarray) -> None:
    """Write a MINC1 displacement volume as volume_io writes it.

    Only the spatial dimensions have a variable.
    """
    netcdf = pytest.importorskip("scipy.io").netcdf_file
    stored = np.transpose(field, (2, 1, 0, 3)).astype("float32")
    f = netcdf(str(path), "w", version=1)
    for name, length in zip(FILE_ORDER, stored.shape):
        f.createDimension(name, length)
    for name in FILE_ORDER[:3]:
        variable = f.createVariable(name, "d", ())
        variable.spacing = b"regular__"
        variable.step = 1.0
    f.createVariable("image", "f", FILE_ORDER)[:] = stored
    for name in ("image-min", "image-max"):
        f.createVariable(name, "d", ())
    f.close()


def _world(index: tx.Sequence[float]) -> np.ndarray:
    """Return the MINC world coordinates of a voxel of the grid."""
    cosines = np.asarray(COSINES).T
    return cosines @ (np.asarray(START) + np.asarray(index) * STEP)


def _apply(xform: tx.Any, points: np.ndarray) -> np.ndarray:
    """Map points through a transformation."""
    points = xforms.CoordinatesField(field=np.asarray(points, float))
    if isinstance(xform, (xforms.Sequence, list)):
        chain = list(xform)
    else:
        chain = [xform]
    out = xforms.Sequence(transformations=[points, *chain]).compute()
    return np.asarray(out.to(xforms.CoordinatesField).field)


def _affine_apply(matrix: np.ndarray, points: np.ndarray) -> np.ndarray:
    return points @ matrix[:3, :3].T + matrix[:3, 3]


NODES = [(1, 2, 3), (0, 0, 0), (3, 4, 5), (2, 1, 1)]


def _smooth_field() -> np.ndarray:
    """Return displacements that vary slowly and linearly over a grid.

    The grid is larger than `SHAPE`, so that its interior is far enough
    from the edges, where the inverse is less accurate.
    """
    shape = (12, 12, 12)
    index = np.stack(np.meshgrid(*map(np.arange, shape), indexing="ij"), -1)
    return 0.5 + 0.1 * index[..., ::-1]


def _grid_file(
    tmp_path: Path, inverted: bool = False, smooth: bool = False
) -> Path:
    field = _smooth_field() if smooth else _field()
    _write_grid(tmp_path / "nl_grid_0.mnc", field)
    path = tmp_path / "nl.xfm"
    path.write_text(_libminc([("grid", "nl_grid_0.mnc", inverted)]))
    return path


