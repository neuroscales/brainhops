@pytest.mark.parametrize(
    "order",
    [FILE_ORDER, ("vector_dimension", "xspace", "zspace", "yspace")],
    ids=["libminc", "permuted"],
)
def test_a_grid_transform_displaces_the_nodes(
    tmp_path: Path, order: tx.Tuple[str, ...]
) -> None:
    field = _field()
    _write_grid(tmp_path / "nl_grid_0.mnc", field, order)
    path = tmp_path / "nl.xfm"
    path.write_text(_libminc([("grid", "nl_grid_0.mnc", False)]))
    chain = io.load(path)
    assert type(chain) is XfmTransform
    # The volume is read lazily.
    assert "_cache_data" not in vars(chain.rawdata[0])
    grid = chain[0]
    assert isinstance(grid, XfmGridTransform)
    # libminc's grid_transform_point maps x to x + d(x), with d in world
    # millimetres along x, y and z.
    points = np.array([_world(node) for node in NODES])
    expected = points + np.array([field[node] for node in NODES])
    np.testing.assert_allclose(_apply(grid, points), expected, atol=1e-5)


def test_an_inverted_grid_transform_reads_as_its_inverse(
    tmp_path: Path,
) -> None:
    path = _grid_file(tmp_path, inverted=True, smooth=True)
    inverse = io.load(path)[0]
    forward = XfmTransform.from_text(
        _libminc([("grid", str(tmp_path / "nl_grid_0.mnc"), False)])
    )[0]
    points = np.array([_world(node) for node in [(5, 6, 6), (6.5, 5, 7)]])
    there = _apply(inverse, points)
    np.testing.assert_allclose(_apply(forward, there), points, atol=0.01)
    inverse_back = XfmTransform.load(path)
    inverse_back.save(tmp_path / "copy.xfm")
    assert (tmp_path / "copy.xfm").read_bytes() == path.read_bytes()


def test_a_grid_file_is_copied_with_its_volume(tmp_path: Path) -> None:
    path = _grid_file(tmp_path)
    chain = io.load(path)
    other = tmp_path / "other"
    other.mkdir()
    chain.save(other / "renamed.xfm")
    assert (other / "renamed.xfm").read_bytes() == path.read_bytes()
    volume = (tmp_path / "nl_grid_0.mnc").read_bytes()
    assert (other / "nl_grid_0.mnc").read_bytes() == volume
    # Beside the volume, nothing is copied, and the file can be saved over
    # itself.
    chain.save(tmp_path / "renamed.xfm")
    chain.save(path)
    assert sorted(p.name for p in tmp_path.iterdir()) == [
        "nl.xfm",
        "nl_grid_0.mnc",
        "other",
        "renamed.xfm",
    ]
    assert np.isfinite(np.asarray(io.load(path)[0].displacement.data)).all()


def test_a_decoded_grid_is_reused_in_an_assigned_chain(
    tmp_path: Path,
) -> None:
    chain = io.load(_grid_file(tmp_path))
    grid = chain[0]
    chain.transformations = [xforms.Affine(SECOND, **RAS), grid]
    (tmp_path / "out").mkdir()
    chain.save(tmp_path / "out" / "both.xfm")
    back = io.load(tmp_path / "out" / "both.xfm")
    assert [type(t) for t in back] == [xforms.Affine, XfmGridTransform]
    assert back.metadata.raw.transforms[1].volume == "nl_grid_0.mnc"
    assert (tmp_path / "out" / "nl_grid_0.mnc").exists()


