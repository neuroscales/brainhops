    assert affine.metadata is metadata
    consolidated = affine.consolidate()
    assert consolidated.metadata.raw.comments == metadata.raw.comments
    np.testing.assert_allclose(consolidated.matrix, SECOND)
    np.testing.assert_allclose(XfmAffine.from_text(text).matrix, TALAIRACH)


