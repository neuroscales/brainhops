"""MNI transform files (`.xfm`), the transforms of the MINC toolkit.

The MINC toolkit, CIVET and FreeSurfer save registrations as MNI
transform files. FreeSurfer's `mri/transforms/talairach.xfm`, which maps
a subject to the MNI305 space, is one of them.

```python
from brainhops import io

affine = io.load("talairach.xfm")        # an XfmAffine
affine.matrix                            # (3, 4), scanner RAS -> MNI305 RAS
chain = io.load("nonlinear.xfm")         # an XfmTransform
affine.save("copy.xfm")                  # the same bytes, comments included
```

## Specification

The syntax and the meaning of the file follow libminc
(BIC-MNI/libminc, commit e71e590): the reader `input_transform` and the
writer `output_transform` in `volume_io/MNI_formats/gen_xf_io.c`, the
tokens of `volume_io/MNI_formats/mni_io.c`, the transforms of
`volume_io/MNI_formats/gen_xfs.c` and the grid transforms of
`volume_io/MNI_formats/grid_transforms.c`.

### 1. Syntax

A file is text. It starts with the line `MNI Transform File`, which is
followed by one or more transforms:

```text
MNI Transform File
%Generated by mri_robust_register src orig.mgz dst mni305.mgz

Transform_Type = Linear;
Linear_Transform =
 1.05 0.01 -0.02 -1.5
 -0.01 1.10 0.08 -17.25
 0.02 -0.09 1.02 12.75;
Transform_Type = Grid_Transform;
Displacement_Volume = nonlinear_grid_0.mnc;
```

A comment starts with `%` or `#` and ends with the line. Whitespace and
comments are skipped between tokens, so the line breaks of a block do not
matter. Each transform starts with `Transform_Type = <type>;`, may then
set `Invert_Flag = True;` or `Invert_Flag = False;`, and holds the
parameters of its type:

| `Transform_Type`              | Parameters                              |
| ----------------------------- | --------------------------------------- |
| `Linear`                      | `Linear_Transform =`, 12 numbers, `;`   |
| `Grid_Transform`              | `Displacement_Volume =`, a name, `;`    |
| `Thin_Plate_Spline_Transform` | `Number_Dimensions`, `Points`, and more |

The 12 numbers of a linear transform are given row by row.

The matrix of a linear transform is the top `(3, 4)` part of a
homogeneous matrix, whose last row is `0 0 0 1`. libminc writes each
number with `%.15g`. brainhops writes the shortest text that reads back
as the same number. libminc ends a number at a space, a semicolon or a
line break, and brainhops also ends it at a tab.

### 2. World and direction

Every transform maps world coordinates to world coordinates. The world
of MINC is RAS: x increases to the right, y to the anterior and z to the
superior, in millimetres (see [`brainhops.io.common.minc`][]). A
transform maps the world of the source image to that of the target
image. `mincresample -transformation` resamples a source image onto a
target grid with the inverse of the transform, because it pulls each
target voxel from the source (`mincresample.c` in BIC-MNI/minc-tools,
commit e382598, which inverts the transform it reads unless
`-invert_transformation` is given). FreeSurfer applies the matrix of
`talairach.xfm` to scanner RAS coordinates of the subject to get MNI305
RAS coordinates (`MRIworldToTalairach` in `utils/mri.cpp`,
freesurfer/freesurfer, commit 4f8728e). Both agree, and the matrix of a
file is read as it is stored, as a map from `RASmm` to `RASmm`.

`Invert_Flag = True;` makes libminc apply the inverse of the transform
(`create_inverse_general_transform` in `input_one_transform`), and
brainhops reads the inverse as well. libminc never writes the flag for a
linear transform, but writes the inverse matrix instead. FreeSurfer
ignores the flag.

### 3. Concatenation

The transforms of a file are applied in the order of the file:
`concat_general_transforms` applies the first, then the second. This is
also the order of a brainhops
[`Sequence`][brainhops.datamodel.transformations.Sequence].

### 4. Grid transforms

A grid transform names a MINC volume, which libminc writes beside the
transform file as `<name>_grid_<n>.mnc` and names without its directory.
A relative name is relative to the directory of the transform file
(`input_one_transform`). The volume has the spatial dimensions `xspace`,
`yspace` and `zspace`, in any order, and one other dimension of three
components, usually `vector_dimension` (`create_grid_transform`).
Component `c` is the displacement along world axis `c`, in millimetres,
and a world point `x` is mapped to `x + d(x)`, where `d` interpolates the
displacements at `x` (`grid_transform_point`). libminc interpolates with
cubic interpolating splines, which it lowers to linear and nearest
interpolation near the edges, and applies no displacement at more than
half a voxel outside the grid. brainhops interpolates with cubic B-splines
of the values and a zero boundary, which agree at the nodes of the grid
(see [`XfmGridTransform`][]). libminc inverts a grid transform by an
iteration, and brainhops by the inverse of the data model, so the two
inverses agree only approximately.

## Classes

A file of one linear transform is read as an [`XfmAffine`][], and any
other file as an [`XfmTransform`][], the chain of its transforms. Both
hold an [`XfmMetadata`][], whose [`XfmRaw`][] record holds the whole file,
including its text, so that a file that is read and written without
changes is written byte for byte. The displacement volumes of an
[`XfmTransform`][] are read as
[`MincImage`][brainhops.io.images.minc.MincImage] objects, which read
their voxels only when the chain is decoded.

!!! note "Limitations"
    brainhops cannot write MINC volumes, so a grid transform is written
    only as the volume that it was read from, which is copied beside the
    new file. MINC1 volumes written by libminc have no variable for
    `vector_dimension`, which the MINC reader of brainhops refuses, so
    only MINC2 displacement volumes are read. Thin-plate splines are read
    and written back unchanged, but cannot be decoded. FreeSurfer reads
    the source and target volumes of an affine from a `%Generated by`
    comment, which the record keeps as a comment.
"""

